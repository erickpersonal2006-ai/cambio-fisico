#!/usr/bin/env bash
# Instalador GTA 6 Clipper (edición española, Chromebook / Linux).
# Uso, en la Terminal de Linux:  bash instalar-gta6.sh
# Guarda todo en la carpeta ~/gta 6 (en Archivos: "Archivos de Linux" > "gta 6").
set -e
BASE="$HOME/gta 6"
SKILLS="$HOME/.claude/skills"
echo "== GTA 6 Clipper para Chromebook =="
echo "Carpeta: $BASE"
mkdir -p "$BASE/skills" "$SKILLS"

# 1. Extraer las skills (conserva .venv y modelos si ya existían)
TMPD="$(mktemp -d)"
LINE=$(awk '/^__ARCHIVO__$/{print NR + 1; exit 0}' "$0")
tail -n +"$LINE" "$0" | base64 -d | tar -xz -C "$TMPD"
for s in gta6-clipper gta6-live-clipper; do
  mkdir -p "$BASE/skills/$s"
  cp -r "$TMPD/skills/$s/." "$BASE/skills/$s/"
  # Claude Code busca las skills en ~/.claude/skills: enlace a la carpeta gta 6
  if [ -e "$SKILLS/$s" ] && [ ! -L "$SKILLS/$s" ]; then mv "$SKILLS/$s" "$SKILLS/$s.antiguo.$(date +%s)"; fi
  ln -sfn "$BASE/skills/$s" "$SKILLS/$s"
done
rm -rf "$TMPD"
echo "  [ok]      Skills copiadas en $BASE/skills y enlazadas en $SKILLS"

# 2. Claude Code (si aún no está instalado en Linux)
export PATH="$HOME/.local/bin:$PATH"
if ! command -v claude >/dev/null 2>&1; then
  echo "  [install] Claude Code"
  curl -fsSL https://claude.ai/install.sh | bash >/dev/null 2>&1 || true
  command -v claude >/dev/null 2>&1 && echo "  [ok]      Claude Code" || echo "  [warn]    Claude Code no se instaló. Instálalo con: curl -fsSL https://claude.ai/install.sh | bash"
else
  echo "  [ok]      Claude Code ya instalado"
fi
grep -q '.local/bin' "$HOME/.bashrc" 2>/dev/null || echo 'export PATH="$HOME/.local/bin:$PATH"' >> "$HOME/.bashrc"

# 3. Dependencias: FFmpeg, Deno, uv, Python, Whisper (multilingüe), detector de caras (~800 MB)
echo
set +e
bash "$BASE/skills/gta6-clipper/scripts/setup.sh"
RC=$?
echo
if [ $RC -eq 0 ]; then
  echo "LISTO. Cierra y vuelve a abrir la Terminal, escribe: claude"
  echo "y luego: clipea este vídeo <enlace de YouTube>"
else
  echo "Faltan cosas (mira las líneas [MISSING]). Vuelve a ejecutar: bash instalar-gta6.sh"
fi
exit $RC
